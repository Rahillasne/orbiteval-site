"""Export the Release Record data file for orbiteval.com.

The page at record.html is a rendering surface, nothing more. Every verdict and
every number it shows is computed here, by the Release Record engine, and
written into release-record-data.js. The page does no arithmetic and holds no
copy of the verdict logic, because two implementations of a decision rule drift
and the one people read is the one that is wrong.

Two real corpora. No synthetic data anywhere.

Corpus 1  NHTSA Standing General Order automated-driving incident reports, per
          event, read from the snapshot this repository already carries at
          release-check/ads.csv. Field incident record, filed with a regulator.
          It carries no vendor claim, so the claim verdict is `no claim on
          file`. Inventing a claim to fill that slot would be the fabricated
          demo this product exists to argue against.

Corpus 2  Twenty published robot-policy claims with citations, as published
          summaries: 12 of the 20 state an episode count per arm, and 8 do
          not. A summary carries no way to check who deployed what or how
          much exposure was accumulated, so identity and exposure here are
          DECLARED BY THE SUBMITTER and the page says so on every row. The
          engine takes them as caller assertions; this exporter records that
          they were assertions.

BOUND BY THE OVERLAP REGISTER. Rejection rates and calibration may be
published; a retraining-noise magnitude may not. This module emits counts,
percentages, a difference, interval bounds and a detection limit. It emits no
sigma, no variance, no seed-to-seed spread, and no per-run or per-seed vector
under any name. It reads Corpus 2 v2 through research/audit_corpus/corpus2.py
at `--corpus2-dir`, the one module allowed to read that file, and never any
top-level field such as `external_median_sigma_pp`, which is tracked
separately and is not to reach the Release Record.

The golden check below is the real test of this file. Each record is rendered
through the engine's own renderer and must appear verbatim in GOLDEN.txt. If
the engine changes and the page would have shown something else, the build
fails here rather than publishing a record that no longer matches the tool.

Usage:
    python3 build/release_record_export.py [--engine PATH] [--corpus2-dir PATH]
                                            [--out PATH]
"""
import argparse
import csv
import hashlib
import json
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
SITE = os.path.dirname(HERE)
sys.path.insert(0, HERE)
from canonical import canonical  # noqa: E402  (needs the path above)

DEFAULT_ENGINE = os.path.expanduser(
    "~/Orbit-Research/product/release_record")
DEFAULT_CORPUS2 = os.path.expanduser("~/Orbit-Research/research/audit_corpus")
DEFAULT_OUT = os.path.join(SITE, "release-record-data.json")

NO_COUNT_NOTE = (
    "the paper states no single episode count for this comparison, so no arm "
    "totals were derived and no detection limit was computed; a reading or a "
    "lower bound is not a count")


def load_corpus2(corpus2_dir):
    sys.path.insert(0, corpus2_dir)
    import corpus2  # noqa: E402
    return corpus2


# The NHTSA snapshot this repository carries. NHTSA republishes the file
# monthly and overwrites it in place, so the hash is pinned: if the CSV is
# refreshed the figures change and the build must stop rather than quietly
# publish a record against evidence the committed page never checked.
NHTSA_CSV = os.path.join(SITE, "release-check", "ads.csv")
NHTSA_SHA256 = "f856d0b9cedc5f4447515c200eeacdff5d4cabf63003dcac207385eb466ff7f5"
NHTSA_URL = "https://static.nhtsa.gov/odi/ffdd/sgo-2021-01/"
NHTSA_FILE = "SGO-2021-01_Incident_Reports_ADS.csv"
NHTSA_PULLED = "2026-09-21"
NHTSA_ENTITY = "Waymo LLC"

# Injury severities counted as the measured outcome, as in the engine's own
# corpora run. Unchanged here: this exporter drives the engine, it does not
# redefine what the engine measures.
SEVERE = {"Moderate W/ Hospitalization", "Moderate W/O Hospitalization",
          "Serious W/ Hospitalization", "Fatality"}

BASELINE = "5th Generation ADS, Version 10"
CANDIDATE = "5th Generation ADS, Version 11"


class ExportError(RuntimeError):
    pass


def require_engine(path):
    """The Release Record engine, or a hard failure naming what is missing."""
    if not os.path.isdir(path):
        raise ExportError(
            "Release Record engine not found at {}\n"
            "  record.html is generated by running the engine, which lives in "
            "the Orbit-Research repository on branch engine-vnext.\n"
            "  Restore it or pass --engine PATH pointed at that branch's "
            "product/release_record. The site is NOT rebuilt and "
            "record.html still shows the previous records.".format(path))
    for f in ("release_record.py", "GOLDEN.txt"):
        if not os.path.exists(os.path.join(path, f)):
            raise ExportError(
                "engine at {} is incomplete: missing {}".format(path, f))
    sys.path.insert(0, path)
    return path


def sha256(path):
    with open(path, "rb") as f:
        return hashlib.sha256(f.read()).hexdigest()


def pct(x):
    return None if x is None else round(x, 4)


def display_strings(rec):
    """Every figure the page prints, preformatted here.

    The page is forbidden from doing arithmetic, and rounding is arithmetic:
    a detection limit shown to one decimal where the engine reports two is a
    different number. These use the engine's own format strings, so what the
    page prints is what the tool printed.
    """
    d = {
        "events_used": "{} (-{} duplicate, -{} superseded)".format(
            rec.events_used, rec.duplicates_removed, rec.revisions_superseded),
    }
    if rec.difference_pp is None:
        return d
    d.update({
        "baseline": "{}/{} = {:.2f}%".format(
            rec.k_baseline, rec.n_baseline, rec.pct_baseline),
        "candidate": "{}/{} = {:.2f}%".format(
            rec.k_candidate, rec.n_candidate, rec.pct_candidate),
        "difference": "{:+.2f} pp".format(rec.difference_pp),
        "interval": "[{:+.2f}, {:+.2f}]".format(rec.ci_low_pp, rec.ci_high_pp),
        "detection_limit": "{:.2f} pp".format(rec.mde_pp),
        "detection_limit_full": "{:.2f} pp at 80% power, alpha 0.05".format(
            rec.mde_pp),
    })
    return d


def record_fields(rec, engine):
    """The engine's record as plain data. Verdict strings are copied, never
    recomputed, and never mapped onto a different vocabulary."""
    return {
        "display": display_strings(rec),
        "baseline_label": rec.baseline_label,
        "candidate_label": rec.candidate_label,
        "measure": rec.measure,
        "claim_text": rec.claim_text,

        "identity": rec.identity,
        "exposure": rec.exposure,
        "claim": rec.claim,
        "sufficiency": rec.sufficiency,
        "mde_basis": rec.mde_basis,

        "n_baseline": rec.n_baseline,
        "k_baseline": rec.k_baseline,
        "pct_baseline": pct(rec.pct_baseline),
        "n_candidate": rec.n_candidate,
        "k_candidate": rec.k_candidate,
        "pct_candidate": pct(rec.pct_candidate),
        "difference_pp": pct(rec.difference_pp),
        "ci_low_pp": pct(rec.ci_low_pp),
        "ci_high_pp": pct(rec.ci_high_pp),
        "mde_pp": pct(rec.mde_pp),

        "events_in": rec.events_in,
        "events_used": rec.events_used,
        "duplicates_removed": rec.duplicates_removed,
        "revisions_superseded": rec.revisions_superseded,
        "unlabelled": rec.unlabelled,
        "flagged_for_adjudication": list(rec.flagged_for_adjudication),
        "merged_variants": list(rec.merged_variants),
        "notes": list(rec.notes),

        # The engine's own plain-text rendering, carried verbatim so the page
        # can show the tool's output rather than only the site's styling of it.
        "rendered": rec.render(),
    }


def build_nhtsa(engine):
    from release_record import Claim, Event, build_record

    got = sha256(NHTSA_CSV)
    if got != NHTSA_SHA256:
        raise ExportError(
            "NHTSA snapshot has changed.\n"
            "  expected {}\n  found    {}\n"
            "  NHTSA overwrites this file monthly. Re-pin the hash only "
            "together with a re-read of the figures.".format(
                NHTSA_SHA256, got))

    with open(NHTSA_CSV, encoding="utf-8-sig", errors="replace") as f:
        rows = [r for r in csv.DictReader(f)
                if r["Reporting Entity"].strip() == NHTSA_ENTITY]
    events = [Event(event_id=r["Report ID"].strip(),
                    event_time=r["Incident Date"].strip(),
                    release_label=r["Automation Feature Version"].strip(),
                    outcome=1 if (r["Highest Injury Severity Alleged"] or
                                  "").strip() in SEVERE else 0,
                    exposure=None,          # the SGO record carries no miles
                    revision=int(r["Report Version"].strip() or 1))
              for r in rows]

    rec = build_record(events, Claim(
        text="", measure="moderate-or-worse injury",
        baseline=BASELINE, candidate=CANDIDATE, effect_pp=None))

    out = record_fields(rec, engine)
    out.update({
        "id": "nhtsa",
        "claim_form": None,
        "effect_pp": None,
        "replication_unit": "event",
        # Both verdicts below were derived from the uploaded events, not taken
        # on trust, which is the whole difference between this corpus and the
        # next one.
        "identity_declared": False,
        "exposure_declared": False,
        "paper": None,
        "citation_key": None,
        "provenance": "{} reports filed by {}".format(len(rows), NHTSA_ENTITY),
    })
    return out


def build_corpus2(engine, corpus2_dir):
    from release_record import Claim, build_record, build_record_from_counts

    corpus2 = load_corpus2(corpus2_dir)
    out = []
    for i, c in enumerate(corpus2.load()["claims"]):
        n = corpus2.stated_n(c)
        # The page is user-facing, so the record carries the names a reader
        # knows (pi0.5, FAST, ...). The engine golden and the packet keep the
        # generic internal label 'comparator'.
        cl = Claim(text=c["claim"], baseline=c["baseline_display"],
                   candidate=c["candidate_display"], measure=c["level"],
                   effect_pp=c["delta_pp"], replication_unit="retrain")
        if n is None:
            # No count stated: the engine's own no-comparison path, which in
            # v0.2 reports the detection limit as not computed.
            rec = build_record([], cl)
            if rec.mde_pp is not None or rec.mde_basis != "not computed":
                raise ExportError(
                    "engine at {} is older than v0.2: a no-comparison record "
                    "must say its detection limit was not computed, not "
                    "print {!r} for a limit that does not exist.\n"
                    "  Build the preview against Orbit-Research branch "
                    "engine-vnext: pass --engine pointed at its "
                    "product/release_record.".format(engine, rec.mde_basis))
            rec.notes.append(NO_COUNT_NOTE)
        else:
            # Arm totals from the rates the paper printed. No design rate:
            # none was pre-specified, so the limit is the observed one.
            rec = build_record_from_counts(
                n, round(c["baseline_rate"] * n), n, round(c["candidate_rate"] * n),
                cl, identity="unknown", exposure="missing")
        row = record_fields(rec, engine)
        row.update({
            "id": "claim-{:02d}".format(i + 1),
            "claim_form": cl.claim_form,
            "effect_pp": c["delta_pp"],
            "replication_unit": "retrain",
            "identity_declared": True,
            "exposure_declared": True,
            "paper": c["paper"],
            "citation_key": c["citation_key"],
            "n_status": c["n_status"],
            "provenance": " ".join("p.{}: “{}”".format(q["page"], q["quote"])
                                   for q in c["n_basis"]),
            "below_detection_limit": None if n is None
            else rec.mde_pp > abs(c["delta_pp"]),
        })
        row["display"]["claimed"] = "{:+.1f} pp".format(c["delta_pp"])
        out.append(row)
    return out, corpus2.CORPUS_PATH


def check_golden(engine, nhtsa, corpus2):
    """Every record must match the engine's committed golden output.

    The page is downstream of the engine. If the two disagree, the page is
    wrong, and a build that publishes it anyway would ship a record that the
    tool itself no longer produces.
    """
    with open(os.path.join(engine, "GOLDEN.txt")) as f:
        golden = f.read()

    problems = []
    if nhtsa["rendered"] not in golden:
        problems.append("the NHTSA record is not in GOLDEN.txt verbatim")

    for row in corpus2:
        if row["n_status"] == "stated":
            line = ("{:<16}{:>7}{:>8.1f}p{:>7.2f}p  {:<9}{:<15}{}".format(
                row["paper"][:15], row["n_baseline"], row["effect_pp"],
                row["mde_pp"], "below" if row["below_detection_limit"] else "above",
                row["sufficiency"], row["claim"]))
        else:
            line = ("{:<16}{:>7}{:>8.1f}p{:>8}  {:<9}{:<15}{}".format(
                row["paper"][:15], "?", row["effect_pp"], "-", "no limit",
                row["sufficiency"], row["claim"]))
        if line not in golden:
            problems.append("row not in GOLDEN.txt: {!r}".format(line))

    if problems:
        raise ExportError(
            "GOLDEN MISMATCH -- refusing to write the page data.\n"
            "  {}\n"
            "  The engine and the page disagree. Re-run the engine's own "
            "corpora check before touching the site.".format(
                "\n  ".join(problems)))


def build(engine, corpus2_dir):
    nhtsa = build_nhtsa(engine)
    corpus2, corpus2_path = build_corpus2(engine, corpus2_dir)
    check_golden(engine, nhtsa, corpus2)

    from release_record import __doc__ as engine_doc
    engine_name = engine_doc.splitlines()[0].rstrip(".")

    return {
        "generated_by": "build/release_record_export.py",
        "engine": engine_name,
        "sources": {
            "nhtsa": {
                "key": "nhtsa",
                "name": "NHTSA Standing General Order, ADS incident reports",
                "label": "NHTSA: field incident record, regulator-filed",
                "evidence_class": "field incident record, regulator-filed",
                "file": NHTSA_FILE,
                "url": NHTSA_URL,
                "pulled": NHTSA_PULLED,
                "sha256": NHTSA_SHA256,
                "checked": ("Release labels and outcomes were read per event, "
                            "so identity and exposure were derived from the "
                            "evidence rather than taken on trust."),
            },
            "corpus2": {
                "key": "corpus2",
                "name": "Twenty published robot-policy claims, with citations",
                "label": ("Corpus 2: published summary; identity and exposure "
                          "declared by submitter"),
                "evidence_class": "published summary, count stated for 12 of 20, no per-event file",
                "file": "audit_corpus_v2.json",
                "url": None,
                "pulled": None,
                "sha256": sha256(corpus2_path),
                "checked": ("A published summary carries no per-event file, so "
                            "identity and exposure could not be checked. Both "
                            "were declared by the submitter."),
            },
            "upload": {
                "key": "upload",
                "name": "Your own evidence file",
                "label": "Upload: execution unavailable on this static site",
                "evidence_class": "not run",
                "available": False,
            },
        },
        "nhtsa": nhtsa,
        "corpus2": corpus2,
        "counts": {
            "records": 1 + len(corpus2),
            "nhtsa_records": 1,
            "corpus2_records": len(corpus2),
            "corpus2_below_limit": sum(1 for r in corpus2
                                       if r["below_detection_limit"]),
            "corpus2_no_count": sum(1 for r in corpus2
                                    if r["n_status"] != "stated"),
        },
    }


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--engine", default=DEFAULT_ENGINE)
    ap.add_argument("--corpus2-dir", default=DEFAULT_CORPUS2)
    ap.add_argument("--out", default=DEFAULT_OUT)
    args = ap.parse_args()

    try:
        engine = require_engine(args.engine)
    except ExportError as e:
        print("\nEXPORT FAILED\n  {}".format(e), file=sys.stderr)
        return 1

    try:
        data = canonical(build(engine, args.corpus2_dir))
    except ExportError as e:
        print("\nEXPORT FAILED\n  {}".format(e), file=sys.stderr)
        return 1

    with open(args.out, "w") as f:
        json.dump(data, f, indent=1)
        f.write("\n")
    js_out = os.path.splitext(args.out)[0] + ".js"
    with open(js_out, "w") as f:
        f.write("// Generated by build/release_record_export.py. Do not edit.\n")
        f.write("window.RELEASE_RECORD = ")
        json.dump(data, f, indent=1)
        f.write(";\n")

    c = data["counts"]
    print("wrote {}".format(args.out))
    print("  engine: {} at {}".format(data["engine"], engine))
    print("  {} records ({} NHTSA, {} published claims)".format(
        c["records"], c["nhtsa_records"], c["corpus2_records"]))
    print("  NHTSA: identity {}, exposure {}, claim {}, sufficiency {}".format(
        data["nhtsa"]["identity"], data["nhtsa"]["exposure"],
        data["nhtsa"]["claim"], data["nhtsa"]["sufficiency"]))
    print("  {} of {} published claims sit below their detection limit".format(
        c["corpus2_below_limit"], c["corpus2_records"]))
    print("  golden: every record matches GOLDEN.txt verbatim")


if __name__ == "__main__":
    sys.exit(main())
